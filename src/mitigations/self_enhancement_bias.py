import re
from typing import Dict, Any, List, Optional, Tuple

class SelfEnhancementMitigator:
    """
    Mitigates and measures Self-Enhancement Bias:
    LLM judges systematically favor outputs generated by models from their own family
    (e.g., Llama judges favor Llama outputs; GPT judges favor GPT outputs).

    Mitigation Strategies:
    1. Cross-Family Verification: Ensure the Judge model family differs from the Generator model family.
    2. Model Family Detection: Normalizes model names (Llama, GPT, Mistral, Claude, Gemini, DeepSeek).
    3. Self-Enhancement Measurement: Computes score and win-rate differentials when judging same-family vs cross-family outputs.
    """

    MODEL_FAMILY_MAP = {
        "llama": ["llama", "meta", "alpaca", "vicuna"],
        "gpt": ["gpt", "openai", "o1", "o3", "davinci"],
        "claude": ["claude", "anthropic"],
        "gemini": ["gemini", "palm", "gemma", "google"],
        "mistral": ["mistral", "mixtral", "codestral"],
        "deepseek": ["deepseek"],
        "qwen": ["qwen", "alibaba"],
    }

    CROSS_FAMILY_INSTRUCTION = (
        "CRITICAL INSTRUCTION - COMBAT SELF-ENHANCEMENT BIAS:\n"
        "- Do NOT favor answers simply because they match your native training style, formatting conventions, or tokenizer quirks.\n"
        "- Disregard model family signatures (e.g. typical markdown styles, bullet hierarchy, default disclaimers).\n"
        "- Focus exclusively on objective factual truth, mathematical correctness, and prompt constraints."
    )

    @classmethod
    def detect_model_family(cls, model_name: Optional[str]) -> str:
        if not model_name:
            return "unknown"
        name_lower = model_name.lower()
        for family, keywords in cls.MODEL_FAMILY_MAP.items():
            for kw in keywords:
                if kw in name_lower:
                    return family
        return "other"

    @classmethod
    def check_cross_family_compliance(
        cls, 
        judge_model: str, 
        generator_model: Optional[str]
    ) -> Dict[str, Any]:
        """
        Validates if judge and generator belong to distinct families.
        """
        judge_family = cls.detect_model_family(judge_model)
        gen_family = cls.detect_model_family(generator_model)

        is_same_family = (judge_family != "unknown" and judge_family == gen_family)

        return {
            "judge_model": judge_model,
            "judge_family": judge_family,
            "generator_model": generator_model,
            "generator_family": gen_family,
            "is_cross_family": not is_same_family,
            "self_enhancement_risk": "HIGH" if is_same_family else "LOW",
            "recommendation": (
                f"Swap judge or generator to a different model family (both are '{judge_family}') "
                f"to eliminate self-enhancement bias."
                if is_same_family
                else "Clean cross-family evaluation: no self-enhancement risk detected."
            )
        }

    @classmethod
    def calculate_self_enhancement_differential(
        cls,
        same_family_scores: List[float],
        cross_family_scores: List[float]
    ) -> Dict[str, Any]:
        """
        Measures the empirical self-enhancement bias:
        Difference in mean score between same-family outputs and cross-family outputs.
        """
        if not same_family_scores or not cross_family_scores:
            return {
                "same_family_mean": 0.0,
                "cross_family_mean": 0.0,
                "score_differential": 0.0,
                "bias_detected": False
            }

        mean_same = sum(same_family_scores) / len(same_family_scores)
        mean_cross = sum(cross_family_scores) / len(cross_family_scores)
        diff = round(mean_same - mean_cross, 3)

        return {
            "same_family_mean": round(mean_same, 3),
            "cross_family_mean": round(mean_cross, 3),
            "score_differential": diff,
            "bias_detected": diff > 0.25 # If judge awards >0.25 pts higher to own family
        }
